// --- Handle submission ---
function handleSubmit() {
  if (mode === 'daily') {
    handleDailySubmit();
    return;
  }

  if (resolving) return;

  const attempt = input.value.trim().toLowerCase();
  if (!attempt) return;

  const correctWord = state.currentWord.toLowerCase();
  const isCorrect = attempt === correctWord;

  input.classList.remove('correct', 'incorrect');

  if (isCorrect) {
    state.correctCount++;
    state.wordsPlayed++;
    resolving = true;
    feedback.textContent = `Correct — "${state.currentWord}" is spelled right.`;
    feedback.className = 'feedback correct';
    input.classList.add('correct');
    updateStats();
    playCorrectSound();
    incrementGoal();

    setTimeout(() => {
      input.value = '';
      input.classList.remove('correct');
      feedback.textContent = '';
      resolving = false;
      pickWord();
      input.focus();
    }, 5000);
    return;
  }

  // Incorrect attempt
  state.triesLeft--;
  input.classList.add('incorrect');
  playIncorrectSound();

  if (state.triesLeft > 0) {
    feedback.textContent = `Not quite — ${state.triesLeft} ${state.triesLeft === 1 ? 'try' : 'tries'} left.`;
    feedback.className = 'feedback incorrect';
    updateTriesDisplay();
    setTimeout(() => {
      input.value = '';
      input.classList.remove('incorrect');
    }, 5000);
  } else {
    // Out of tries — mark as missed, reveal the word, move on
    state.wordsPlayed++;
    resolving = true;
    feedback.textContent = `Out of tries — the word was "${state.currentWord}".`;
    feedback.className = 'feedback incorrect';
    updateStats();
    updateTriesDisplay();
    incrementGoal();

    setTimeout(() => {
      input.value = '';
      input.classList.remove('incorrect');
      feedback.textContent = '';
      resolving = false;
      pickWord();
      input.focus();
    }, 5000);
  }
}

